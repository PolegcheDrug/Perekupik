function getRandomBarnCarImage(carObj) {
    if (!carObj) return "";
    if (carObj.images && carObj.images.length > 0) {
        const randomIndex = Math.floor(Math.random() * carObj.images.length);
        return carObj.images[randomIndex];
    }
    return carObj.img || "";
}

